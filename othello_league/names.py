class NameRegistry:
    """
    「名字＋名前」の組み合わせでフルネームを生成する（例：藤井聡太）。
    名字×名前の組み合わせは非常に多いが、それでも重複した場合のみ連番を付ける
    （例：同じ「藤井聡太」が2人生まれたら「藤井聡太2」）。
    """
    def __init__(self, counts=None):
        self.counts = dict(counts) if counts else {}

    def generate(self):
        full_name = random.choice(SURNAMES) + random.choice(GIVEN_NAMES)
        self.counts[full_name] = self.counts.get(full_name, 0) + 1
        n = self.counts[full_name]
        return full_name if n == 1 else f"{full_name}{n}"

    def to_dict(self):
        return dict(self.counts)

    @staticmethod
    def from_dict(d):
        return NameRegistry(d or {})
